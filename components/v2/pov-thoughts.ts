const firstWord = (t: string) => t.split(' ')[0].toLowerCase()

/**
 * Перемешивает мысли: каждая тема равномерно размазана по всему списку (большая тема не идёт
 * через раз), затем соседей одной темы или с одним первым словом разводим перестановкой.
 * `first` — мысль, с которой начать (чтобы первая строка совпадала на сервере и в браузере).
 */
export function mixThoughts(rand: () => number, first?: string): string[] {
  const items: Array<{ t: string; theme: string; key: number }> = []
  for (const [theme, list] of Object.entries(THEMES)) {
    const l = [...list]
    for (let k = l.length - 1; k > 0; k--) {
      const j = Math.floor(rand() * (k + 1))
      ;[l[k], l[j]] = [l[j], l[k]]
    }
    const off = rand()
    l.forEach((t, k) => items.push({ t, theme, key: (k + off) / l.length + (rand() - 0.5) * 0.08 }))
  }
  items.sort((a, b) => a.key - b.key)
  if (first) {
    const i = items.findIndex((x) => x.t === first)
    items.unshift(...items.splice(i, 1))
  }
  const clash = (a: (typeof items)[0], b: (typeof items)[0]) => a.theme === b.theme || firstWord(a.t) === firstWord(b.t)
  for (let i = 1; i < items.length; i++) {
    if (!clash(items[i - 1], items[i])) continue
    const j = items.findIndex((x, k) => k > i && !clash(items[i - 1], x) && (k + 1 >= items.length || !clash(items[i], items[k + 1])))
    if (j > 0) [items[i], items[j]] = [items[j], items[i]]
  }
  return items.map((x) => x.t)
}

/** Детерминированный генератор для постоянного порядка (одинаковый на сервере и в браузере) */
function seeded(seed: number) {
  return () => {
    seed = (seed * 1664525 + 1013904223) % 4294967296
    return seed / 4294967296
  }
}

export const THOUGHTS = mixThoughts(seeded(1411))
