/** Максимум по ключу: И3 даёт 33 (5+3+3+5+5+2+10), а не 30, как пишут источники */
const keyMax = (symptoms: readonly SymptomId[]) =>
  symptoms.reduce((s, id) => s + KEY[id].reduce((t, [, , p]) => t + p, 0), 0)

