const ANSWERS: Array<{ value: number; label: string; answer: Answer }> = [
  { value: 1, label: 'Да', answer: 'да' },
  { value: 0, label: 'Нет', answer: 'нет' },
]

const PHASE_IDS = Object.keys(PHASES) as PhaseId[]
const SYMPTOM_IDS = PHASE_IDS.flatMap((p) => [...PHASES[p].symptoms]) as SymptomId[]
const phaseOf = (symptom: SymptomId) => PHASE_IDS.find((p) => (PHASES[p].symptoms as readonly string[]).includes(symptom))!

/**
 * Сборка вариантов: за ответ-триггер вариант получает балл ключа в свой
 * симптом, в фазу этого симптома и в итог. Вклады суммируются, поэтому
 * пункт, записанный в ключе дважды, учёлся бы дважды — как на бумаге.
 */
const items: Item[] = TEXTS.map((text, i) => {
  const n = i + 1
  const entries = SYMPTOM_IDS.flatMap((symptom) =>
    KEY[symptom].filter(([item]) => item === n).map(([, trigger, points]) => ({ symptom, trigger, points })),
  )
  const options = ANSWERS.map(({ value, label, answer }) => {
    // Несовпавший ответ явно даёт 0 — так min подшкалы считается верно
    const scores: Record<string, number> = {}
    for (const { symptom, trigger, points } of entries) {
      const pts = trigger === answer ? points : 0
      for (const id of [symptom, phaseOf(symptom), 'total']) scores[id] = (scores[id] ?? 0) + pts
    }
    return { value, label, scores }
  })
  return { id: String(n), text, options, part: 'main' }
})

