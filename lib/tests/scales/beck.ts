/** Ключ подшкал по Тарабриной: пп. 1–13 когнитивно-аффективная, 14–21 соматическая */
const subscaleOf = (n: number) => (n <= 13 ? 'ca' : 'sp')

/**
 * У бланка нет заголовков пунктов — только номер и четыре утверждения,
 * поэтому text пустой: интерфейс показывает номер пункта.
 */
const numbered: Item[] = statements.map((group, i) => {
  const n = i + 1
  return {
    id: String(n),
    text: '',
    part: 'main',
    hint: HINT,
    options: group.map((label, value) => ({
      value,
      label,
      scores: { total: value, [subscaleOf(n)]: value },
    })),
  }
})

