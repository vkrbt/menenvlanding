/**
 * Сборщик пунктов: прямой пункт даёт вклад = value, обратный — 5 − value.
 * Это ровно формула Ханина Σпрям − Σобр + 5·n_обр (+50 для РТ, +35 для ЛТ).
 */
function buildItems(
  firstId: number,
  texts: string[],
  labels: string[],
  reverse: number[],
  subscale: 'state' | 'trait',
): Item[] {
  return texts.map((text, i) => {
    const n = firstId + i
    const reversed = reverse.includes(n)
    return {
      id: String(n),
      text,
      part: subscale,
      options: labels.map((label, j) => {
        const value = j + 1
        return { value, label, scores: { [subscale]: reversed ? 5 - value : value } }
      }),
    }
  })
}

