/**
 * Варианты ответа: value — балл источника (M05/M98), индекс в строке KEY = value − 1.
 * Порядок показа — от «постоянно или всегда» к «никогда не было», то есть
 * по убыванию частоты, как читают шкалу частоты; совпадает с возрастанием балла.
 * Баллы берутся по value, а не по позиции: порядок можно менять без пересчёта.
 */
const ANSWERS: Array<{ value: 1 | 2 | 3 | 4 | 5; label: string }> = [
  { value: 1, label: 'Постоянно или всегда' },
  { value: 2, label: 'Часто' },
  { value: 3, label: 'Иногда' },
  { value: 4, label: 'Редко' },
  { value: 5, label: 'Никогда не было' },
]

const SUBSCALE_IDS = Object.keys(KEY) as YmSubscaleId[]

function rowsFor(question: number): Array<[YmSubscaleId, Row]> {
  return SUBSCALE_IDS.flatMap((id) => {
    const row = (KEY[id] as Record<number, Row>)[question]
    return row ? [[id, row] as [YmSubscaleId, Row]] : []
  })
}

const items: Item[] = QUESTIONS.map((text, i) => {
  const rows = rowsFor(i + 1)
  const options: Option[] = ANSWERS.map(({ value, label }) => ({
    value,
    label,
    scores: Object.fromEntries(rows.map(([id, row]) => [id, row[value - 1]])),
  }))
  return { id: String(i + 1), text, options, part: 'main' }
})

