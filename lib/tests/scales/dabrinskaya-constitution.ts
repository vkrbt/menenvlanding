/** Номера категорий — они же голоса в scores.type */
const W = 0
const M = 1
const S = 2
const R = 3

type Vote = typeof W | typeof M | typeof S | typeof R | null

/** Варианты в порядке бланка: [текст, за какую конституцию голосует] */
const options = (list: Array<[string, Vote]>): Option[] =>
  list.map(([label, vote], value): Option => ({ value, label, scores: vote === null ? {} : { type: vote } }))

