  'Рост делим на длину ноги. Сбоку бедра находим место, где наибольшее отложение жира (там находится большой вертел бедренной кости, можно ориентироваться по запястью), и измеряем расстояние от него до пола. Например, 165 см / 85 см = 1,94 — это трохантерный индекс.'

const HAIR_HINT = 'Если было удаление волос (эпиляция), отвечаем, какая была ранее.'

/** Замер вместо ручного выбора: индекс в сотых → номер варианта (value) по полосам автора */
const tiMeasure = (bands: Array<{ upTo: number; value: number }>, warn: string): Measure => ({
  a: { label: 'Рост', hint: 'без обуви, от пола до макушки' },
  b: { label: 'Длина ноги', hint: 'от пола до большого вертела бедренной кости' },
  unit: 'см',
  result: 'Трохантерный индекс',
  bands,
  plausible: { min: 170, max: 230 },
  warn,
})

