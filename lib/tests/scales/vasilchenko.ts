/**
 * Градации общего индекса (§3.3.2): «1 (1–1,5) — чрезвычайно слабая;
 * 2 (1,6–2,5) — очень слабая …». В сотых: граница x,5 — у нижней ступени.
 * severity — группа из шапки таблицы: слабая / средняя / сильная.
 */
const LEVELS: Array<[string, string, 0 | 1 | 2]> = [
  ['1', 'чрезвычайно слабая', 0],
  ['2', 'очень слабая', 0],
  ['3', 'слабая', 0],
  ['4', 'несколько ослабленный вариант средней', 1],
  ['5', 'средняя', 1],
  ['6', 'сильный вариант средней', 1],
  ['7', 'сильная', 2],
  ['8', 'очень сильная', 2],
  ['9', 'чрезвычайно сильная', 2],
]

const categories = (): Category[] =>
  LEVELS.map(([n, label, severity], i) => ({
    id: `level-${n}`,
    min: i === 0 ? 100 : i * 100 + 51,
    max: i === LEVELS.length - 1 ? 900 : i * 100 + 150,
    label,
    severity,
  }))

const mean = (id: string, title: string): Subscale => ({
  id,
  title,
  min: 100,
  max: 900,
  divisor: 100,
  aggregate: 'mean',
  categories: categories(),
})

