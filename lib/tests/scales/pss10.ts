/** Обратные (позитивно сформулированные) пункты: S3 и R2 (§2.3) */
export const REVERSE = [4, 5, 7, 8]

const LABELS = ['Никогда', 'Почти никогда', 'Иногда', 'Часто', 'Очень часто']

const STEM = 'В течение прошедшего месяца как часто Вы'

const texts = [
  'расстраивались из-за того, что происходило неожиданно?',
  'чувствовали, что не способны контролировать важные моменты своей жизни?',
  'нервничали и испытывали стресс?',
  'чувствовали уверенность в своей способности справляться с личными проблемами?',
  'чувствовали, что все идет так, как это нужно Вам?',
  'обнаруживали, что не можете справиться со всем, что Вам приходилось делать?',
  'могли контролировать свою раздражительность?',
  // Редакционная правка: у Золотаревой «чувствовали, что находитесь на вершине
  // успеха?» — буквальный перевод идиомы «on top of things». Формулировка
  // «владеете ситуацией» — из версии Абабкова и соавт. (2016), §4.1.
  'чувствовали, что владеете ситуацией?',
  'злились из-за того, что происходило без контроля с Вашей стороны?',
  'чувствовали, что Вам не преодолеть всех скопившихся трудностей?',
]

const items: Item[] = texts.map((text, i) => {
  const n = i + 1
  const reversed = REVERSE.includes(n)
  return {
    id: String(n),
    text: `${STEM} ${text}`,
    options: LABELS.map((label, value) => ({ value, label, scores: { total: reversed ? 4 - value : value } })),
  }
})

