export function explanation(
  slug: string,
  subscale: string,
  severity: number,
  categoryId?: string,
): Explanation | undefined {
  const s = severity as 0 | 1 | 2 | 3
  if (categoryId && BY_CATEGORY[slug]?.[categoryId]) return BY_CATEGORY[slug][categoryId]
  if (slug === 'yakhin-mendelevich') return YM_COMMON[s]
  return COPY[slug]?.[subscale]?.[s]
}

