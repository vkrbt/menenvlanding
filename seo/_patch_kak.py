#!/usr/bin/env python3
"""Apply patch_kak edits to kak-perestat-sryvatsya-na-blizkih.md"""
from pathlib import Path

p = Path("drafts/writing/kak-perestat-sryvatsya-na-blizkih.md")
t = p.read_text()

# 1. Intro (vygoranie style)
i = t.index("Проверь себя")
j = t.index("## Как «просто успокойся»")
intro = (
    "Пятница, дверь закрылась — и на кухне вылетает «Отстань» на нормальный вопрос жены. "
    "Ребёнок пролил сок, дети притихают, ты стыдишься, извиняешься, обещаешь «больше не буду». "
    "Через неделю то же самое. Знакомая картина?\n\n"
    "Я гештальт-терапевт и параллельно много лет работаю разработчиком в большой компании — "
    "тему знаю с двух сторон, и из кресла, и из опенспейса. "
    "Расскажу, что происходит внутри, когда броня падает дома, "
    "и что из популярных советов работает, а что — красивый мусор.\n\n"
)
t = t[:i] + intro + t[j:]

# 2. Remove "Полистай комментарии… я подожду"
t = t.replace(
    "Полистай комментарии под любым постом про срыв, прямо сейчас можешь, я подожду. ",
    "",
)

# 3. Remove "половины наших участников"
t = t.replace("кусочек из половины наших участников", "узнаваемый тип")

# 4. Shorten Andrey
old_andrey = (
    "Маршрут номер два — поломка. У меня был участник, Андрей, сорок пять, инженер — "
    "собирательный, не выдумываю. После срыва на сына за пролитый сок он не мог зайти "
    "в квартиру полчаса: стоял у мусорных баков, курил сигарету, которую бросил три года "
    "назад, и смотрел на подъезд как на чужой город. Жена написала «ты где» — он ответил "
    "«скоро». Вечером гуглил «как перестать срываться», получил «считай до десяти». "
    "Ага, конечно. Похмелье, слыхал я, тоже коньяком лечат. Знать бы ещё, где такое "
    "лечение заканчивается."
)
new_andrey = (
    "Маршрут номер два — поломка. Андрей, сорок пять, инженер — собирательный портрет. "
    "После срыва на сына за пролитый сок не мог зайти в квартиру полчаса: стоял у "
    "мусорных баков и смотрел на подъезд как на чужой город. Жена написала «ты где» — "
    "ответил «скоро». Вечером гуглил «как перестать срываться», получил «считай до "
    "десяти». Совет слабый — знаю по себе."
)
t = t.replace(old_andrey, new_andrey)

# 5. Specialist section + short CTA before FAQ
old_cta = """<!-- CTA -->

**Место, где можно снять витрину**

Раз в две недели десять мужчин три часа разговаривают о жизни — без «просто успокойся», без «стань лучше» и без нетворкинга. Тема срывов всплывает сама, её приносят участники. Ведут гештальт-терапевт и психиатр. Начни с созвона-знакомства на 15 минут.

_Бесплатно и ни к чему не обязывает._

## Частые вопросы"""

new_cta = """## Когда нужен специалист

Если срывы сопровождаются ударами, угрозами, разрушением вещей — это уже не «устал», а повод идти к психологу или психиатру без отговорок. То же самое, если семья боится тебя дома, а ты сам после каждого эпизода думаешь «я монстр». Злость как сигнал перегруза — одна история. Злость как способ управлять близкими — другая, и там самопомощь не тянет.

<!-- CTA -->

**Мужская среда** — раз в две недели десять мужчин, три часа, без коучинга. Тема срывов всплывает сама. Созвон-знакомство — 15 минут, бесплатно.

## Частые вопросы"""

t = t.replace(old_cta, new_cta)

p.write_text(t)
print("patch_kak applied")
